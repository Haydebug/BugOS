// Clipboard history, Windows style (BugOS › Clipboard). Press ⌃⌥V (or your own shortcut): the last things
// you copied (text, images, files), newest first. ↑ ↓ and Return (or click) pastes one into the app you were
// in; pin the ones you want to keep. Pinned items survive restarts (saved in Application Support/BugDock);
// the rest live in memory only, like Windows. Anything a password manager marks as secret is never kept.
import AppKit
import BugOSKit
import Carbon.HIToolbox
import SwiftUI

struct ClipItem: Identifiable, Equatable {
    enum Kind: Equatable { case text(String), image(Data), files([URL]) }
    let id: UUID
    let kind: Kind
    let date: Date
    let source: String?
    var pinned = false

    static func == (a: ClipItem, b: ClipItem) -> Bool { a.id == b.id && a.pinned == b.pinned }

    func sameContent(as o: ClipItem) -> Bool { kind == o.kind }

    var preview: String {
        switch kind {
        case .text(let t): return t
        case .image: return "Image"
        case .files(let u): return u.map(\.lastPathComponent).joined(separator: ", ")
        }
    }
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    @Published private(set) var items: [ClipItem] = []
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var ignoreCount: Int?

    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping",
    ]
    static var enabled: Bool { UserDefaults.standard.object(forKey: ClipboardSetting.enabled) as? Bool ?? true }
    static var limit: Int { UserDefaults.standard.object(forKey: ClipboardSetting.limit) as? Int ?? 25 }

    private static var store: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("BugDock/Clipboard", isDirectory: true)
    }

    func reload() {
        if Self.enabled {
            if timer == nil {
                loadPinned()
                lastCount = NSPasteboard.general.changeCount
                timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
                    MainActor.assumeIsolated { ClipboardHistory.shared.check() }
                }
            }
            trim()
        } else {
            timer?.invalidate(); timer = nil
            items.removeAll { !$0.pinned }
        }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        if ignoreCount == pb.changeCount { ignoreCount = nil; return }   // our own paste
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secretTypes) else { return }   // passwords: never kept
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        var kind: ClipItem.Kind?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            kind = .files(urls)
        } else if let img = NSImage(pasteboard: pb), types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
                  let tiff = img.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
                  let png = rep.representation(using: .png, properties: [:]), png.count < 25_000_000 {
            kind = .image(png)
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, s.utf8.count < 1_000_000 {
            kind = .text(s)
        }
        guard let kind else { return }
        let item = ClipItem(id: UUID(), kind: kind, date: Date(), source: source)
        // The same thing again: move it to the top instead of a duplicate.
        if let i = items.firstIndex(where: { $0.sameContent(as: item) }) {
            var old = items.remove(at: i)
            old = ClipItem(id: old.id, kind: old.kind, date: Date(), source: source, pinned: old.pinned)
            items.insert(old, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
    }

    private func trim() {
        var unpinned = 0
        items = items.filter { $0.pinned || { unpinned += 1; return unpinned <= Self.limit }() }
    }

    /// Put an item back on the clipboard (without adding it to the history again).
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text(let t): pb.setString(t, forType: .string)
        case .image(let d): pb.setData(d, forType: .png); if let i = NSImage(data: d) { pb.writeObjects([i]) }
        case .files(let u): pb.writeObjects(u as [NSURL])
        }
        ignoreCount = pb.changeCount
        lastCount = pb.changeCount
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        savePinned()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        if item.pinned { savePinned() }
    }

    /// For testing: how many items of each kind (never their contents) into BugOS's log.
    func logSummary() {
        var t = 0, i = 0, f = 0
        for it in items { switch it.kind { case .text: t += 1; case .image: i += 1; case .files: f += 1 } }
        let line = "\(Date()) Taskbar clipboard: \(items.count) items (\(t) text, \(i) images, \(f) files, \(items.filter(\.pinned).count) pinned)\n"
        if let h = try? FileHandle(forWritingTo: URL(fileURLWithPath: NSHomeDirectory() + "/Library/Logs/Bug OS.log")) {
            h.seekToEndOfFile(); h.write(Data(line.utf8)); try? h.close()
        }
    }

    /// Clear all: everything but the pinned ones (like Windows).
    func clear() { items.removeAll { !$0.pinned } }

    // MARK: Pinned items on disk

    private func savePinned() {
        let fm = FileManager.default
        try? fm.removeItem(at: Self.store)
        try? fm.createDirectory(at: Self.store, withIntermediateDirectories: true)
        var list: [[String: String]] = []
        for (i, it) in items.filter(\.pinned).enumerated() {
            switch it.kind {
            case .text(let t): list.append(["kind": "text", "text": t])
            case .files(let u): list.append(["kind": "files", "paths": u.map(\.path).joined(separator: "\n")])
            case .image(let d):
                let name = "pin-\(i).png"
                try? d.write(to: Self.store.appendingPathComponent(name))
                list.append(["kind": "image", "file": name])
            }
        }
        (list as NSArray).write(to: Self.store.appendingPathComponent("pinned.plist"), atomically: true)
    }

    private func loadPinned() {
        guard items.isEmpty, let list = NSArray(contentsOf: Self.store.appendingPathComponent("pinned.plist")) as? [[String: String]] else { return }
        for d in list {
            var kind: ClipItem.Kind?
            switch d["kind"] {
            case "text": kind = d["text"].map(ClipItem.Kind.text)
            case "files": kind = d["paths"].map { .files($0.split(separator: "\n").map { URL(fileURLWithPath: String($0)) }) }
            case "image": kind = d["file"].flatMap { try? Data(contentsOf: Self.store.appendingPathComponent($0)) }.map(ClipItem.Kind.image)
            default: break
            }
            if let kind { items.append(ClipItem(id: UUID(), kind: kind, date: Date(), source: nil, pinned: true)) }
        }
    }
}

// MARK: The popup

@MainActor
final class ClipboardPanel {
    static let shared = ClipboardPanel()
    private let panel = KeyablePanel(level: .popUpMenu)
    private let model = ClipPanelModel()
    private var returnTo: NSRunningApplication?
    private var localKeys: Any?
    private var clickMonitor: Any?
    private var hotKey: EventHotKeyRef?
    private var handlerInstalled = false

    var isOpen: Bool { panel.isVisible }

    // MARK: Shortcut (⌃⌥V unless changed; "" = none)

    static var shortcut: Shortcut? {
        guard let s = UserDefaults.standard.string(forKey: ClipboardSetting.shortcut) else { return ClipboardSetting.defaultShortcut }
        return Shortcut(stored: s)
    }

    func reload() {
        if let r = hotKey { UnregisterEventHotKey(r); hotKey = nil }
        ClipboardHistory.shared.reload()
        guard ClipboardHistory.enabled, let k = Self.shortcut else { return }
        if !handlerInstalled {
            handlerInstalled = true
            var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            InstallEventHandler(GetApplicationEventTarget(), { _, event, _ in
                var hk = EventHotKeyID()
                GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID),
                                  nil, MemoryLayout<EventHotKeyID>.size, nil, &hk)
                guard hk.signature == OSType(0x4243_4C50) else { return OSStatus(eventNotHandledErr) }   // "BCLP"
                DispatchQueue.main.async { MainActor.assumeIsolated { ClipboardPanel.shared.toggle() } }
                return noErr
            }, 1, &spec, nil, nil)
        }
        RegisterEventHotKey(k.keyCode, k.mods, EventHotKeyID(signature: OSType(0x4243_4C50), id: 1), GetApplicationEventTarget(), 0, &hotKey)
    }

    func pauseShortcut() { if let r = hotKey { UnregisterEventHotKey(r); hotKey = nil } }

    func toggle() { isOpen ? close() : open() }

    func open() {
        returnTo = NSWorkspace.shared.frontmostApplication
        model.selected = ClipboardHistory.shared.items.first?.id
        panel.contentView = ClickThroughHostingView(rootView: ClipPanelView(history: ClipboardHistory.shared, model: model,
            pick: { [weak self] in self?.paste($0) }, close: { [weak self] in self?.close() }))
        // Near the pointer, on its screen.
        let size = NSSize(width: 360, height: 470)
        let p = NSEvent.mouseLocation
        let s = (NSScreen.screens.first { NSMouseInRect(p, $0.frame, false) } ?? NSScreen.main!).visibleFrame
        let x = min(max(p.x - size.width / 2, s.minX + 8), s.maxX - size.width - 8)
        let y = min(max(p.y - size.height - 12, s.minY + 56), s.maxY - size.height - 8)
        panel.setFrame(NSRect(x: x, y: y, width: size.width, height: size.height), display: true)
        panel.hasShadow = true
        NSApp.activate(ignoringOtherApps: true)
        panel.makeKeyAndOrderFront(nil)
        localKeys = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] e in
            guard let self else { return e }
            return MainActor.assumeIsolated {
                switch Int(e.keyCode) {
                case kVK_UpArrow: self.step(-1); return nil
                case kVK_DownArrow: self.step(1); return nil
                case kVK_Return, kVK_ANSI_KeypadEnter:
                    if let id = self.model.selected, let it = ClipboardHistory.shared.items.first(where: { $0.id == id }) { self.paste(it) }
                    return nil
                case kVK_Escape: self.close(); return nil
                case kVK_Delete, kVK_ForwardDelete:
                    if let id = self.model.selected, let it = ClipboardHistory.shared.items.first(where: { $0.id == id }) {
                        self.step(1); ClipboardHistory.shared.delete(it)
                    }
                    return nil
                default: return e
                }
            }
        }
        clickMonitor = NSEvent.addGlobalMonitorForEvents(matching: [.leftMouseDown, .rightMouseDown]) { [weak self] _ in
            MainActor.assumeIsolated { self?.close() }
        }
    }

    func close(handBack: Bool = true) {
        guard isOpen else { return }
        for m in [localKeys, clickMonitor].compactMap({ $0 }) { NSEvent.removeMonitor(m) }
        localKeys = nil; clickMonitor = nil
        panel.orderOut(nil)
        if handBack { returnTo?.activate() }
    }

    private func step(_ d: Int) {
        let items = ClipboardHistory.shared.items
        guard !items.isEmpty else { return }
        let i = items.firstIndex { $0.id == model.selected } ?? -1
        model.selected = items[max(0, min(items.count - 1, i + d))].id
    }

    /// Copy it, go back to the app you were in, and paste (⌘V) there.
    private func paste(_ item: ClipItem) {
        ClipboardHistory.shared.copy(item)
        let app = returnTo
        close(handBack: false)
        app?.activate()
        guard UserDefaults.standard.object(forKey: ClipboardSetting.pasteNow) as? Bool ?? true else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }
}

@MainActor
final class ClipPanelModel: ObservableObject { @Published var selected: UUID? }

struct ClipPanelView: View {
    @ObservedObject var history: ClipboardHistory
    @ObservedObject var model: ClipPanelModel
    let pick: (ClipItem) -> Void
    let close: () -> Void

    var body: some View {
        VStack(spacing: 0) {
            HStack {
                Text("Clipboard").font(.system(size: 14, weight: .semibold))
                Spacer()
                Button("Clear all") { history.clear() }
                    .buttonStyle(.plain).font(.system(size: 12)).foregroundStyle(.secondary)
                    .disabled(!history.items.contains { !$0.pinned })
            }
            .padding(.horizontal, 14).padding(.top, 12).padding(.bottom, 8)
            if history.items.isEmpty {
                Spacer()
                VStack(spacing: 6) {
                    Image(systemName: "doc.on.clipboard").font(.system(size: 26)).foregroundStyle(.secondary)
                    Text("Nothing here yet").font(.system(size: 13, weight: .medium))
                    Text("Things you copy show up here.").font(.system(size: 11.5)).foregroundStyle(.secondary)
                }
                Spacer()
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 6) {
                            ForEach(history.items) { item in
                                ClipRow(item: item, selected: model.selected == item.id,
                                        pin: { history.togglePin(item) }, delete: { history.delete(item) })
                                    .id(item.id)
                                    .onTapGesture { pick(item) }
                                    .onHover { if $0 { model.selected = item.id } }
                            }
                        }
                        .padding(.horizontal, 10).padding(.bottom, 10)
                    }
                    .onChange(of: model.selected) { _, id in if let id { proxy.scrollTo(id) } }
                }
            }
        }
        .frame(width: 360, height: 470)
        .background(VisualEffect(material: .hudWindow))
        .clipShape(RoundedRectangle(cornerRadius: 12, style: .continuous))
        .overlay(RoundedRectangle(cornerRadius: 12, style: .continuous).strokeBorder(Color.white.opacity(0.14), lineWidth: 0.5))
        .environment(\.colorScheme, .dark)
    }
}

struct ClipRow: View {
    let item: ClipItem
    let selected: Bool
    let pin: () -> Void
    let delete: () -> Void

    var body: some View {
        HStack(alignment: .top, spacing: 8) {
            VStack(alignment: .leading, spacing: 5) {
            Group {
                switch item.kind {
                case .text(let t):
                    Text(t.trimmingCharacters(in: .whitespacesAndNewlines)).font(.system(size: 12.5)).lineLimit(4)
                        .frame(maxWidth: .infinity, alignment: .leading)
                case .image(let d):
                    if let img = NSImage(data: d) {
                        Image(nsImage: img).resizable().aspectRatio(contentMode: .fit).frame(maxHeight: 110)
                            .clipShape(RoundedRectangle(cornerRadius: 5)).frame(maxWidth: .infinity, alignment: .leading)
                    }
                case .files(let urls):
                    HStack(spacing: 8) {
                        Image(nsImage: NSWorkspace.shared.icon(forFile: urls[0].path)).resizable().frame(width: 28, height: 28)
                        Text(item.preview).font(.system(size: 12.5)).lineLimit(2)
                    }
                    .frame(maxWidth: .infinity, alignment: .leading)
                }
            }
            // Where it was copied from, on its own line under it.
            if let src = item.source {
                Text(src).font(.system(size: 10)).foregroundStyle(.tertiary)
            }
            }
            VStack(spacing: 6) {
                Button(action: pin) {
                    Image(systemName: item.pinned ? "pin.fill" : "pin").font(.system(size: 11))
                        .foregroundStyle(item.pinned ? Color(nsColor: BugOSColor.accent) : .secondary)
                }.buttonStyle(.plain).help(item.pinned ? "Unpin" : "Pin (kept after restarts)")
                Button(action: delete) { Image(systemName: "xmark").font(.system(size: 10, weight: .semibold)).foregroundStyle(.secondary) }
                    .buttonStyle(.plain).help("Remove")
            }
            .opacity(selected || item.pinned ? 1 : 0.35)
        }
        .padding(10)
        .background(RoundedRectangle(cornerRadius: 8, style: .continuous).fill(Color.white.opacity(selected ? 0.14 : 0.06)))
        .overlay(RoundedRectangle(cornerRadius: 8, style: .continuous)
            .strokeBorder(selected ? Color(nsColor: BugOSColor.accent).opacity(0.8) : .clear, lineWidth: 1.5))
        .contentShape(Rectangle())
    }
}
